export const supportedInterfaceLocales = ["en", "es", "pt"];

export function validateInterfaceMessages(messages = interfaceMessages) {
    const missing = [];
    Object.entries(messages).forEach(([key, translations]) => {
        supportedInterfaceLocales.forEach((locale) => {
            if (typeof translations[locale] !== "string" || !translations[locale].trim()) {
                missing.push(`${key}.${locale}`);
            }
        });
    });
    return missing;
}

export function interfaceText(locale) {
    const selected = supportedInterfaceLocales.includes(locale) ? locale : "en";
    return Object.fromEntries(
        Object.entries(interfaceMessages).map(([key, translations]) => [key, translations[selected]])
    );
}
