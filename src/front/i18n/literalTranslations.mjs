const reverseCatalogue = new Map();
for (const translations of literalTranslations) {
    Object.values(translations).forEach((value) => {
        if (!reverseCatalogue.has(value)) reverseCatalogue.set(value, translations);
    });
}

export const literalMessage = (value) => reverseCatalogue.get(value);

export function translateLiteral(value, locale) {
    const translations = literalMessage(value);
    return translations?.[locale] || value;
}

export function validateLiteralTranslations() {
    return literalTranslations.flatMap((translations, index) =>
        ["en", "es", "pt"]
            .filter((locale) => !translations[locale]?.trim())
            .map((locale) => `literal.${index}.${locale}`)
    );
}
